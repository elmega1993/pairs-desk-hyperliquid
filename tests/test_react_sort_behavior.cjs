const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require(require.resolve('typescript',{paths:[path.join(__dirname,'../react_frontend')]}));
const vm=require('node:vm');
const code=fs.readFileSync(path.join(__dirname,'../react_frontend/src/sort.ts'),'utf8');
const compiled=ts.transpileModule(code,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const moduleObject={exports:{}};
vm.runInNewContext(compiled,{module:moduleObject,exports:moduleObject.exports});
const {nextSort,sortPairs}=moduleObject.exports;
assert.equal(nextSort('pnl:desc','pnl'),'pnl:asc');
assert.equal(nextSort('pnl:asc','pnl'),'pnl:desc');
assert.equal(nextSort('pnl:asc','funding'),'funding:desc');
const pairs=[{id:'a',long:'AAA',short:'ZZZ',pnl:12,realized:0,funding:-5,size:100,pnl_pct:12},{id:'b',long:'BBB',short:'ZZZ',pnl:-1,realized:100,funding:3,size:400,pnl_pct:-1},{id:'c',long:'CCC',short:'ZZZ',pnl:null,realized:50,funding:null,size:200,pnl_pct:null}];
const ids=(field)=>Array.from(sortPairs(pairs,field),p=>p.id).join(',');
assert.equal(ids('pnl:desc'),'a,b,c');
assert.equal(ids('pnl:asc'),'b,a,c');
assert.equal(ids('realized:desc'),'b,c,a');
assert.equal(ids('funding:desc'),'b,a,c');
assert.equal(ids('size:desc'),'b,c,a');
assert.equal(ids('name:asc'),'a,b,c');
console.log('OK: radar/sidebar sorting toggle, 6 columns, missing values last');
