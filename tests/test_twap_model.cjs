const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require(require.resolve('typescript',{paths:[path.join(__dirname,'../react_frontend')]}));
const src=fs.readFileSync(path.join(__dirname,'../react_frontend/src/twapModel.ts'),'utf8');
const loaded={exports:{}};
vm.runInNewContext(ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module:loaded,exports:loaded.exports,Math,Number,Date});
const {legProgress,twapElapsed,timeDataIndex,twapChartSpan,twapCanCancel,isVerifiedTwapEvent}=loaded.exports;
const leg={coin:'BTC',size:10,executed_size:null,twap_id:17,status:'running'};
assert.equal(legProgress(leg),null,'unknown fills must stay unknown');
assert.equal(legProgress({...leg,executed_size:0}),0);
assert.equal(legProgress({...leg,executed_size:2.5}),25);
assert.equal(legProgress({...leg,executed_size:12}),100);
assert.equal(legProgress({...leg,size:0,executed_size:0}),null);
const job={id:'g1',created_ms:1000,planned_end_ms:61000,updated_ms:16000,status:'running',legs:[leg]};
assert.equal(twapElapsed(job,31000),50);
assert.equal(legProgress(leg),null,'elapsed must never invent fills');
assert.equal(twapElapsed({...job,status:'cancelled'},61000),25);
assert.equal(twapCanCancel(job),true);
assert.equal(twapCanCancel({...job,status:'uncertain',legs:[{...leg,twap_id:null}]}),false);
const bars=[{timestamp:1000},{timestamp:61000},{timestamp:121000}];
assert.equal(timeDataIndex(31000,bars),.5);
assert.equal(timeDataIndex(151000,bars),2.5);
assert.equal(timeDataIndex(-29000,bars),-.5);
assert.equal(twapChartSpan(job,bars,31000).elapsedIndex,.5);
assert.equal(twapChartSpan(job,bars,61000).endIndex,1);
assert.equal(isVerifiedTwapEvent({time:1000,kind:'add'},[job]),false,'time overlap alone cannot suppress a marker');
assert.equal(isVerifiedTwapEvent({twap_group_id:'g1'},[job]),true);
assert.equal(isVerifiedTwapEvent({twap_group_id:'other'},[job]),false);
console.log('OK: native TWAP progress, precise candle-time spans, verified groups');
